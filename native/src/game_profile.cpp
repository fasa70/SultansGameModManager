bool MatchesGameProfile(const GameProfile& profile,
                        std::uintptr_t image_base,
                        std::uintptr_t image_start,
                        std::uintptr_t image_end) {
    for (const auto& fingerprint : profile.fingerprints) {
        if (!MatchesBytes(image_base, image_start, image_end, fingerprint.rva,
                          fingerprint.bytes.data(), fingerprint.bytes.size())) {
            return false;
        }
    }
    return true;
}

bool MatchesTmpGlyphFingerprint(const GameProfile& profile,
                                std::uintptr_t image_base,
                                std::uintptr_t image_start,
                                std::uintptr_t image_end) {
    return MatchesBytes(image_base, image_start, image_end,
                        profile.tmp_glyph.update_rva,
                        profile.tmp_glyph.update_bytes.data(),
                        profile.tmp_glyph.update_bytes.size()) &&
        MatchesBytes(image_base, image_start, image_end,
                     profile.tmp_glyph.call_rva,
                     profile.tmp_glyph.call_bytes.data(),
                     profile.tmp_glyph.call_bytes.size());
}

std::uintptr_t TargetAddress(const GameProfile& profile,
                             HookTarget target,
                             std::uintptr_t image_base) {
    return image_base + profile.fingerprints.at(static_cast<std::size_t>(target)).rva;
}

