bool MatchesBytes(std::uintptr_t base, std::uintptr_t start, std::uintptr_t end,
                  std::uintptr_t rva, const std::uint8_t* bytes, std::size_t size) {
    if (base < start || base >= end || rva > end - base || size > end - base - rva) {
        return false;
    }
    return std::memcmp(reinterpret_cast<const void*>(base + rva), bytes, size) == 0;
}

